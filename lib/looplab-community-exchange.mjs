const STABLE_ID = /^[A-Za-z0-9][A-Za-z0-9._:-]*$/;
const TILED_FLIP_H = 0x80000000 >>> 0;
const TILED_FLIP_V = 0x40000000;
const TILED_FLIP_D = 0x20000000;
const TILED_ROTATE_HEX_120 = 0x10000000;
const TILED_GID_MASK = 0x0fffffff;
const XML_STANDARD_ENTITIES = Object.freeze({ amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" });

const clone = (value) => JSON.parse(JSON.stringify(value));
const finite = (value) => Number.isFinite(Number(value));
const integer = (value) => Number.isInteger(Number(value));
const compareText = (first, second) => String(first).localeCompare(String(second), "en");

function boundedText(value, name, maximum = LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumSourceCharacters) {
  if (typeof value !== "string" || value.length < 1) throw new Error(`${name} must be a non-empty string.`);
  if (value.length > maximum) throw new Error(`${name} exceeds the ${maximum.toLocaleString()} character limit.`);
  return value;
}
function stableId(value, fallback = "exchange") {
  const normalized = String(value ?? "").trim().replace(/[^A-Za-z0-9._:-]+/g, "-").replace(/^[^A-Za-z0-9]+/, "").replace(/-+$/g, "");
  return STABLE_ID.test(normalized) ? normalized : fallback;
}

function sourceReceipt(sourceName, sourceText, format) {
  const text = boundedText(sourceText, "sourceText");
  const name = String(sourceName ?? "").trim() || `import.${format === "tmx" ? "tmx" : "json"}`;
  return {
    sourceName: name,
    format,
    mediaType: format === "tmx" || format === "tsx" ? "application/xml" : "application/json",
    sourceLength: text.length,
    sourceSha256: `sha256:${sha256Hex(text)}`,
    sourceText: text,
  };
}

function decodeXmlEntities(value) {
  return String(value).replace(/&(#x[0-9a-fA-F]+|#[0-9]+|amp|lt|gt|quot|apos);/g, (match, entity) => {
    if (Object.prototype.hasOwnProperty.call(XML_STANDARD_ENTITIES, entity)) return XML_STANDARD_ENTITIES[entity];
    const code = entity.startsWith("#x") ? Number.parseInt(entity.slice(2), 16) : Number.parseInt(entity.slice(1), 10);
    if (!Number.isInteger(code) || code < 0 || code > 0x10ffff) throw new Error(`Invalid XML character entity: ${match}`);
    return String.fromCodePoint(code);
  });
}

function parseXmlAttributes(source) {
  const attributes = {};
  let cursor = 0;
  while (cursor < source.length) {
    while (/\s/.test(source[cursor] ?? "")) cursor += 1;
    if (cursor >= source.length) break;
    const nameStart = cursor;
    while (cursor < source.length && !/[\s=]/.test(source[cursor])) cursor += 1;
    const name = source.slice(nameStart, cursor);
    if (!name) throw new Error("Malformed XML attribute name.");
    while (/\s/.test(source[cursor] ?? "")) cursor += 1;
    if (source[cursor] !== "=") throw new Error(`XML attribute ${name} is missing '='.`);
    cursor += 1;
    while (/\s/.test(source[cursor] ?? "")) cursor += 1;
    const quote = source[cursor];
    if (quote !== '"' && quote !== "'") throw new Error(`XML attribute ${name} must use a quoted value.`);
    cursor += 1;
    const valueStart = cursor;
    while (cursor < source.length && source[cursor] !== quote) cursor += 1;
    if (cursor >= source.length) throw new Error(`XML attribute ${name} has an unterminated value.`);
    if (Object.prototype.hasOwnProperty.call(attributes, name)) throw new Error(`XML attribute ${name} is duplicated.`);
    attributes[name] = decodeXmlEntities(source.slice(valueStart, cursor));
    cursor += 1;
    if (Object.keys(attributes).length > LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumXmlAttributesPerNode) throw new Error("An XML node exceeds the bounded attribute limit.");
  }
  return attributes;
}

function findXmlTagEnd(source, start) {
  let quote = null;
  for (let cursor = start; cursor < source.length; cursor += 1) {
    const character = source[cursor];
    if (quote) {
      if (character === quote) quote = null;
    } else if (character === '"' || character === "'") quote = character;
    else if (character === ">") return cursor;
  }
  throw new Error("XML contains an unterminated tag.");
}

function parseBoundedXml(sourceText) {
  const source = boundedText(sourceText, "XML source");
  const lowered = source.toLowerCase();
  if (lowered.includes("<!doctype") || lowered.includes("<!entity")) throw new Error("DTD and entity declarations are forbidden in imported XML.");
  const root = { name: "#document", attributes: {}, children: [], text: "" };
  const stack = [root];
  let cursor = 0;
  let nodes = 0;
  while (cursor < source.length) {
    const tagStart = source.indexOf("<", cursor);
    if (tagStart < 0) {
      stack.at(-1).text += decodeXmlEntities(source.slice(cursor));
      break;
    }
    if (tagStart > cursor) stack.at(-1).text += decodeXmlEntities(source.slice(cursor, tagStart));
    if (source.startsWith("<!--", tagStart)) {
      const end = source.indexOf("-->", tagStart + 4);
      if (end < 0) throw new Error("XML contains an unterminated comment.");
      cursor = end + 3;
      continue;
    }
    if (source.startsWith("<![CDATA[", tagStart)) {
      const end = source.indexOf("]]>", tagStart + 9);
      if (end < 0) throw new Error("XML contains an unterminated CDATA section.");
      stack.at(-1).text += source.slice(tagStart + 9, end);
      cursor = end + 3;
      continue;
    }
    if (source.startsWith("<?", tagStart)) {
      const end = source.indexOf("?>", tagStart + 2);
      if (end < 0) throw new Error("XML contains an unterminated processing instruction.");
      cursor = end + 2;
      continue;
    }
    if (source.startsWith("<!", tagStart)) throw new Error("Unsupported XML declaration. DTDs and entity expansion are forbidden.");
    const tagEnd = findXmlTagEnd(source, tagStart + 1);
    let body = source.slice(tagStart + 1, tagEnd).trim();
    if (!body) throw new Error("XML contains an empty tag.");
    if (body.startsWith("/")) {
      const name = body.slice(1).trim();
      if (stack.length === 1 || stack.at(-1).name !== name) throw new Error(`XML closing tag ${name} does not match the open element.`);
      stack.pop();
      cursor = tagEnd + 1;
      continue;
    }
    const selfClosing = body.endsWith("/");
    if (selfClosing) body = body.slice(0, -1).trimEnd();
    let nameEnd = 0;
    while (nameEnd < body.length && !/\s/.test(body[nameEnd])) nameEnd += 1;
    const name = body.slice(0, nameEnd);
    if (!name || !/^[A-Za-z_][A-Za-z0-9_.:-]*$/.test(name)) throw new Error(`Invalid XML element name: ${name || "(empty)"}`);
    const node = { name, attributes: parseXmlAttributes(body.slice(nameEnd)), children: [], text: "" };
    stack.at(-1).children.push(node);
    nodes += 1;
    if (nodes > LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumXmlNodes) throw new Error("XML exceeds the bounded node limit.");
    if (!selfClosing) {
      stack.push(node);
      if (stack.length > LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumXmlDepth) throw new Error("XML exceeds the bounded nesting limit.");
    }
    cursor = tagEnd + 1;
  }
  if (stack.length !== 1) throw new Error(`XML element ${stack.at(-1).name} was not closed.`);
  const elements = root.children.filter((node) => node.name !== "#text");
  if (elements.length !== 1) throw new Error("XML must contain exactly one root element.");
  return elements[0];
}

const childNodes = (node, name) => (node?.children ?? []).filter((child) => child.name === name);
const firstChild = (node, name) => childNodes(node, name)[0] ?? null;

function numberAttribute(node, name, fallback = 0) {
  const value = Number(node?.attributes?.[name]);
  return Number.isFinite(value) ? value : fallback;
}

function booleanAttribute(node, name, fallback = false) {
  const value = String(node?.attributes?.[name] ?? "").toLowerCase();
  if (value === "1" || value === "true") return true;
  if (value === "0" || value === "false") return false;
  return fallback;
}

function parseTypedProperty(type, value) {
  if (type === "bool") return String(value).toLowerCase() === "true" || String(value) === "1";
  if (type === "int" || type === "float" || type === "object") return Number(value);
  return value;
}

function xmlProperties(node) {
  const propertiesNode = firstChild(node, "properties");
  if (!propertiesNode) return {};
  return Object.fromEntries(childNodes(propertiesNode, "property").map((property) => {
    const name = String(property.attributes.name ?? "").trim();
    const raw = property.attributes.value ?? property.text ?? "";
    return [name, parseTypedProperty(property.attributes.type ?? "string", raw)];
  }).filter(([name]) => name));
}

function jsonProperties(value) {
  return Object.fromEntries((Array.isArray(value) ? value : []).map((property) => [String(property?.name ?? "").trim(), property?.value]).filter(([name]) => name));
}

function parseCsvData(value) {
  const text = String(value ?? "").trim();
  if (!text) return [];
  return text.split(",").map((entry) => {
    const number = Number(entry.trim());
    if (!Number.isInteger(number) || number < 0 || number > 0xffffffff) throw new Error("Tiled CSV data contains a non-uint32 GID.");
    return number >>> 0;
  });
}

function parseXmlDataNode(dataNode, width, height) {
  const encoding = dataNode?.attributes?.encoding ?? "xml";
  const compression = dataNode?.attributes?.compression ?? "";
  if (compression) throw new Error(`Compressed TMX tile data (${compression}) is preserved in source but cannot be projected in exchange v1.`);
  const readPayload = (node, expected) => {
    const values = encoding === "csv"
      ? parseCsvData(node.text)
      : encoding === "xml"
        ? childNodes(node, "tile").map((tile) => Number(tile.attributes.gid ?? 0) >>> 0)
        : null;
    if (!values) throw new Error(`TMX data encoding ${encoding} is unsupported; use CSV or XML tile elements.`);
    if (values.length !== expected) throw new Error(`TMX tile data contains ${values.length} cells; ${expected} were declared.`);
    return values;
  };
  const chunks = childNodes(dataNode, "chunk");
  if (chunks.length) return chunks.map((chunk) => {
    const chunkWidth = numberAttribute(chunk, "width");
    const chunkHeight = numberAttribute(chunk, "height");
    return { x: numberAttribute(chunk, "x"), y: numberAttribute(chunk, "y"), width: chunkWidth, height: chunkHeight, gids: readPayload(chunk, chunkWidth * chunkHeight) };
  });
  return [{ x: 0, y: 0, width, height, gids: readPayload(dataNode, width * height) }];
}

function parseXmlTileset(node, sourceName) {
  const image = firstChild(node, "image");
  return {
    sourceName,
    name: String(node.attributes.name ?? sourceName ?? "tileset"),
    tileWidth: numberAttribute(node, "tilewidth"),
    tileHeight: numberAttribute(node, "tileheight"),
    tileCount: numberAttribute(node, "tilecount", null),
    columns: numberAttribute(node, "columns", null),
    spacing: numberAttribute(node, "spacing", 0),
    margin: numberAttribute(node, "margin", 0),
    imageSource: image?.attributes?.source ?? null,
    imageWidth: image ? numberAttribute(image, "width", null) : null,
    imageHeight: image ? numberAttribute(image, "height", null) : null,
    properties: xmlProperties(node),
  };
}

function dependencyIndex(dependencies = []) {
  if (!Array.isArray(dependencies) || dependencies.length > LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumDependencies) throw new Error(`dependencies must contain at most ${LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumDependencies} entries.`);
  const index = new Map();
  const receipts = [];
  for (const dependency of dependencies) {
    const name = String(dependency?.sourceName ?? "").trim();
    if (!name) throw new Error("Every dependency requires sourceName.");
    if (index.has(name)) throw new Error(`Dependency ${name} is duplicated.`);
    const text = boundedText(dependency?.sourceText, `Dependency ${name}`, LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumDependencyCharacters);
    const format = dependency?.format === "tsx" ? "tsx" : dependency?.format === "json" ? "json" : name.toLowerCase().endsWith(".tsx") ? "tsx" : "json";
    const receipt = sourceReceipt(name, text, format);
    index.set(name, receipt);
    receipts.push(receipt);
  }
  return { index, receipts };
}

function parseTiledJson(sourceText, dependencies) {
  let document;
  try { document = JSON.parse(sourceText); } catch (error) { throw new Error(`Tiled JSON is invalid: ${error instanceof Error ? error.message : String(error)}`); }
  if (!document || typeof document !== "object" || Array.isArray(document)) throw new Error("Tiled JSON must be an object.");
  const type = document.type ?? "map";
  if (type !== "map") throw new Error(`Expected a Tiled map document, received type ${String(type)}.`);
  const unknownPaths = [];
  const knownMap = new Set(["backgroundcolor", "class", "compressionlevel", "editorsettings", "height", "hexsidelength", "infinite", "layers", "nextlayerid", "nextobjectid", "orientation", "parallaxoriginx", "parallaxoriginy", "properties", "renderorder", "staggeraxis", "staggerindex", "tiledversion", "tileheight", "tilesets", "tilewidth", "type", "version", "width"]);
  for (const key of Object.keys(document)) if (!knownMap.has(key) && unknownPaths.length < LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumUnknownPaths) unknownPaths.push(`$.${key}`);
  const tilesets = (Array.isArray(document.tilesets) ? document.tilesets : []).map((entry, index) => {
    const firstgid = Number(entry?.firstgid);
    if (!Number.isInteger(firstgid) || firstgid < 1) throw new Error(`tilesets[${index}].firstgid must be a positive integer.`);
    if (entry.source) {
      const name = String(entry.source);
      const dependency = dependencies.index.get(name);
      if (!dependency) throw new Error(`External tileset ${name} was not supplied in dependencies.`);
      let parsed;
      if (dependency.format === "tsx") {
        const root = parseBoundedXml(dependency.sourceText);
        if (root.name !== "tileset") throw new Error(`Dependency ${name} is not a TSX tileset.`);
        parsed = parseXmlTileset(root, name);
      } else {
        try { parsed = JSON.parse(dependency.sourceText); } catch (error) { throw new Error(`Tileset dependency ${name} is invalid JSON: ${error instanceof Error ? error.message : String(error)}`); }
        parsed = { ...parsed, sourceName: name, imageSource: parsed.image ?? null };
      }
      return { ...parsed, firstgid, sourceName: name };
    }
    return { ...entry, firstgid, sourceName: entry.name ?? `embedded-${index + 1}`, imageSource: entry.image ?? null };
  }).sort((first, second) => first.firstgid - second.firstgid);
  const layers = [];
  let objectLayerCount = 0;
  const visit = (entries, path = "$.layers", inherited = {}) => {
    for (const [index, layer] of (Array.isArray(entries) ? entries : []).entries()) {
      const currentPath = `${path}[${index}]`;
      if (layer?.type === "group") {
        visit(layer.layers, `${currentPath}.layers`, {
          opacity: Number(inherited.opacity ?? 1) * Number(layer.opacity ?? 1),
          visible: inherited.visible !== false && layer.visible !== false,
          offsetx: Number(inherited.offsetx ?? 0) + Number(layer.offsetx ?? 0),
          offsety: Number(inherited.offsety ?? 0) + Number(layer.offsety ?? 0),
          parallaxx: Number(inherited.parallaxx ?? 1) * Number(layer.parallaxx ?? 1),
          parallaxy: Number(inherited.parallaxy ?? 1) * Number(layer.parallaxy ?? 1),
        });
        continue;
      }
      if (layer?.type === "objectgroup") { objectLayerCount += 1; continue; }
      if (layer?.type !== "tilelayer") continue;
      const width = Number(layer.width ?? document.width);
      const height = Number(layer.height ?? document.height);
      const chunks = Array.isArray(layer.chunks)
        ? layer.chunks.map((chunk) => ({ x: Number(chunk.x), y: Number(chunk.y), width: Number(chunk.width), height: Number(chunk.height), gids: Array.isArray(chunk.data) ? chunk.data.map((gid) => Number(gid) >>> 0) : [] }))
        : [{ x: Number(layer.x ?? 0), y: Number(layer.y ?? 0), width, height, gids: Array.isArray(layer.data) ? layer.data.map((gid) => Number(gid) >>> 0) : typeof layer.data === "string" ? parseCsvData(layer.data) : [] }];
      layers.push({
        id: layer.id ?? layers.length + 1,
        name: layer.name ?? `Layer ${layers.length + 1}`,
        width,
        height,
        offsetX: Number(inherited.offsetx ?? 0) + Number(layer.offsetx ?? 0),
        offsetY: Number(inherited.offsety ?? 0) + Number(layer.offsety ?? 0),
        opacity: Number(inherited.opacity ?? 1) * Number(layer.opacity ?? 1),
        visible: inherited.visible !== false && layer.visible !== false,
        parallaxX: Number(inherited.parallaxx ?? 1) * Number(layer.parallaxx ?? 1),
        parallaxY: Number(inherited.parallaxy ?? 1) * Number(layer.parallaxy ?? 1),
        properties: jsonProperties(layer.properties),
        chunks,
      });
    }
  };
  visit(document.layers);
  return {
    format: "tiled-json",
    document,
    orientation: document.orientation ?? "orthogonal",
    tileWidth: Number(document.tilewidth),
    tileHeight: Number(document.tileheight),
    width: Number(document.width ?? 0),
    height: Number(document.height ?? 0),
    infinite: document.infinite === true,
    tilesets,
    layers,
    objectLayerCount,
    unknownPaths,
    parsedDigest: canonicalSha256(document),
  };
}

function parseTmx(sourceText, dependencies) {
  const root = parseBoundedXml(sourceText);
  if (root.name !== "map") throw new Error(`Expected a TMX <map> root, received <${root.name}>.`);
  const tilesets = childNodes(root, "tileset").map((entry, index) => {
    const firstgid = numberAttribute(entry, "firstgid");
    if (!Number.isInteger(firstgid) || firstgid < 1) throw new Error(`TMX tileset ${index + 1} requires a positive firstgid.`);
    const external = entry.attributes.source;
    if (external) {
      const dependency = dependencies.index.get(external);
      if (!dependency) throw new Error(`External tileset ${external} was not supplied in dependencies.`);
      const dependencyRoot = parseBoundedXml(dependency.sourceText);
      if (dependencyRoot.name !== "tileset") throw new Error(`Dependency ${external} is not a TSX tileset.`);
      return { ...parseXmlTileset(dependencyRoot, external), firstgid };
    }
    return { ...parseXmlTileset(entry, entry.attributes.name ?? `embedded-${index + 1}`), firstgid };
  }).sort((first, second) => first.firstgid - second.firstgid);
  const layers = [];
  let objectLayerCount = childNodes(root, "objectgroup").length;
  const visit = (node, inherited = {}) => {
    for (const child of node.children ?? []) {
      if (child.name === "group") {
        objectLayerCount += childNodes(child, "objectgroup").length;
        visit(child, {
          opacity: Number(inherited.opacity ?? 1) * numberAttribute(child, "opacity", 1),
          visible: inherited.visible !== false && booleanAttribute(child, "visible", true),
          offsetx: Number(inherited.offsetx ?? 0) + numberAttribute(child, "offsetx", 0),
          offsety: Number(inherited.offsety ?? 0) + numberAttribute(child, "offsety", 0),
          parallaxx: Number(inherited.parallaxx ?? 1) * numberAttribute(child, "parallaxx", 1),
          parallaxy: Number(inherited.parallaxy ?? 1) * numberAttribute(child, "parallaxy", 1),
        });
        continue;
      }
      if (child.name !== "layer") continue;
      const width = numberAttribute(child, "width", numberAttribute(root, "width"));
      const height = numberAttribute(child, "height", numberAttribute(root, "height"));
      const data = firstChild(child, "data");
      if (!data) throw new Error(`TMX layer ${child.attributes.name ?? child.attributes.id ?? "unknown"} has no <data>.`);
      layers.push({
        id: child.attributes.id ?? layers.length + 1,
        name: child.attributes.name ?? `Layer ${layers.length + 1}`,
        width,
        height,
        offsetX: Number(inherited.offsetx ?? 0) + numberAttribute(child, "offsetx", 0),
        offsetY: Number(inherited.offsety ?? 0) + numberAttribute(child, "offsety", 0),
        opacity: Number(inherited.opacity ?? 1) * numberAttribute(child, "opacity", 1),
        visible: inherited.visible !== false && booleanAttribute(child, "visible", true),
        parallaxX: Number(inherited.parallaxx ?? 1) * numberAttribute(child, "parallaxx", 1),
        parallaxY: Number(inherited.parallaxy ?? 1) * numberAttribute(child, "parallaxy", 1),
        properties: xmlProperties(child),
        chunks: parseXmlDataNode(data, width, height),
      });
    }
  };
  visit(root);
  const known = new Set(["tileset", "layer", "objectgroup", "group", "properties", "imagelayer"]);
  const unknownPaths = [...new Set((root.children ?? []).filter((node) => !known.has(node.name)).map((node) => `$.map.${node.name}`))].slice(0, LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumUnknownPaths);
  return {
    format: "tmx",
    orientation: root.attributes.orientation ?? "orthogonal",
    tileWidth: numberAttribute(root, "tilewidth"),
    tileHeight: numberAttribute(root, "tileheight"),
    width: numberAttribute(root, "width", 0),
    height: numberAttribute(root, "height", 0),
    infinite: booleanAttribute(root, "infinite", false),
    tilesets,
    layers,
    objectLayerCount,
    unknownPaths,
    parsedDigest: canonicalSha256({ attributes: root.attributes, tilesets, layers, objectLayerCount }),
  };
}

function resolveTiledFormat(sourceName, explicit, sourceText) {
  if (explicit === "tiled-json" || explicit === "tmx") return explicit;
  const name = String(sourceName ?? "").toLowerCase();
  if (name.endsWith(".tmx") || String(sourceText ?? "").trimStart().startsWith("<")) return "tmx";
  return "tiled-json";
}

function mapForProject(project, mapId) {
  const maps = Array.isArray(project?.maps) && project.maps.length ? project.maps : [];
  return maps.find((map) => map.id === mapId) ?? maps.find((map) => map.id === project?.activeMapId) ?? maps[0] ?? null;
}

function normalizeBindingKey(value) {
  return String(value ?? "").trim().replace(/\\/g, "/");
}

function bindingForTileset(tileset, bindings) {
  const keys = [tileset.sourceName, tileset.name, tileset.imageSource].map(normalizeBindingKey).filter(Boolean);
  const exact = bindings.filter((binding) => keys.includes(normalizeBindingKey(binding.sourceName)));
  return exact.length === 1 ? exact[0] : null;
}

function tileSetForGid(tilesets, gid) {
  let selected = null;
  for (const tileset of tilesets) {
    if (tileset.firstgid <= gid) selected = tileset;
    else break;
  }
  return selected;
}

function createSparseChunks(width, height, cells) {
  const chunks = new Map();
  for (const cell of cells) {
    if (!cell.word) continue;
    const chunkX = Math.floor(cell.x / LOOPLAB_TILE_PROGRAM_LIMITS.chunkSize) * LOOPLAB_TILE_PROGRAM_LIMITS.chunkSize;
    const chunkY = Math.floor(cell.y / LOOPLAB_TILE_PROGRAM_LIMITS.chunkSize) * LOOPLAB_TILE_PROGRAM_LIMITS.chunkSize;
    const key = `${chunkX}:${chunkY}`;
    let chunk = chunks.get(key);
    if (!chunk) {
      const chunkWidth = Math.min(LOOPLAB_TILE_PROGRAM_LIMITS.chunkSize, width - chunkX);
      const chunkHeight = Math.min(LOOPLAB_TILE_PROGRAM_LIMITS.chunkSize, height - chunkY);
      chunk = { x: chunkX, y: chunkY, width: chunkWidth, height: chunkHeight, cells: Array(chunkWidth * chunkHeight).fill(0) };
      chunks.set(key, chunk);
    }
    chunk.cells[(cell.y - chunk.y) * chunk.width + (cell.x - chunk.x)] = cell.word >>> 0;
  }
  return [...chunks.values()].sort((first, second) => first.y - second.y || first.x - second.x);
}

function projectionForTiled(parsed) {
  if (!integer(parsed.tileWidth) || !integer(parsed.tileHeight) || parsed.tileWidth < 1 || parsed.tileHeight < 1) throw new Error("Tiled map tilewidth and tileheight must be positive integers.");
  if (parsed.orientation === "orthogonal") return { type: "orthographic", tileWidth: parsed.tileWidth, tileHeight: parsed.tileHeight };
  if (parsed.orientation === "isometric") {
    if (parsed.tileWidth !== 128 || parsed.tileHeight !== 64) throw new Error("LoopLab dimetric imports require exact 128×64 Tiled isometric cells. Normalize the tileset before import rather than stretching collision or art implicitly.");
    return { type: "dimetric-2:1", tileWidth: 128, tileHeight: 64, worldUnitsPerTile: 128 };
  }
  throw new Error(`Tiled orientation ${String(parsed.orientation)} is unsupported in the 2D/2.5D exchange.`);
}

function sameProjection(first, second) {
  return first?.type === second?.type && Number(first?.tileWidth) === Number(second?.tileWidth) && Number(first?.tileHeight) === Number(second?.tileHeight);
}

function buildTiledProjection(project, input, parsed) {
  const map = mapForProject(project, input.mapId);
  if (!map) throw new Error("The selected Tiled import target map was not found.");
  const projection = projectionForTiled(parsed);
  const errors = [];
  const warnings = [];
  if (parsed.layers.length < 1) errors.push("The Tiled map contains no tile layers to project.");
  if (parsed.layers.length > LOOPLAB_TILE_PROGRAM_LIMITS.maximumLayers) errors.push(`The Tiled map exceeds the ${LOOPLAB_TILE_PROGRAM_LIMITS.maximumLayers} visual-layer limit.`);
  if (parsed.objectLayerCount > 0) warnings.push(`${parsed.objectLayerCount} Tiled object layer${parsed.objectLayerCount === 1 ? " was" : "s were"} preserved as exact source evidence but not applied as collision or gameplay geometry.`);
  const bindingInputs = Array.isArray(input.assetBindings) ? input.assetBindings : [];
  const assets = new Map((project.assets ?? []).map((asset) => [asset.id, asset]));
  const referenced = new Map();
  let minX = 0;
  let minY = 0;
  let maxX = Math.max(0, parsed.width);
  let maxY = Math.max(0, parsed.height);
  for (const layer of parsed.layers) {
    if (!Number.isInteger(layer.offsetX / parsed.tileWidth) || !Number.isInteger(layer.offsetY / parsed.tileHeight)) errors.push(`Layer ${layer.name} uses a pixel offset that is not divisible by the declared tile size.`);
    const offsetCellsX = Math.round(layer.offsetX / parsed.tileWidth);
    const offsetCellsY = Math.round(layer.offsetY / parsed.tileHeight);
    for (const chunk of layer.chunks) {
      if (![chunk.x, chunk.y, chunk.width, chunk.height].every(Number.isInteger) || chunk.width < 1 || chunk.height < 1 || chunk.gids.length !== chunk.width * chunk.height) {
        errors.push(`Layer ${layer.name} contains malformed or mismatched chunk data.`);
        continue;
      }
      minX = Math.min(minX, chunk.x + offsetCellsX);
      minY = Math.min(minY, chunk.y + offsetCellsY);
      maxX = Math.max(maxX, chunk.x + offsetCellsX + chunk.width);
      maxY = Math.max(maxY, chunk.y + offsetCellsY + chunk.height);
      for (const raw of chunk.gids) {
        const unsigned = Number(raw) >>> 0;
        const gid = unsigned & TILED_GID_MASK;
        if (!gid) continue;
        const tileset = tileSetForGid(parsed.tilesets, gid);
        if (!tileset) { errors.push(`GID ${gid} does not belong to any declared tileset.`); continue; }
        const localId = gid - tileset.firstgid;
        const key = `${tileset.firstgid}:${localId}`;
        referenced.set(key, { tileset, localId });
        if (unsigned & TILED_ROTATE_HEX_120) warnings.push("One or more GIDs carry Tiled's bit-29 hexagonal rotation flag. The flag is cleared for this non-hexagonal projection and remains preserved only in the exact source envelope.");
      }
    }
  }
  const shiftX = -minX;
  const shiftY = -minY;
  const columns = maxX - minX;
  const rows = maxY - minY;
  if (columns < 1 || rows < 1 || columns > LOOPLAB_TILE_PROGRAM_LIMITS.maximumGridDimension || rows > LOOPLAB_TILE_PROGRAM_LIMITS.maximumGridDimension) errors.push("The normalized Tiled grid is empty or exceeds LoopLab's bounded grid dimensions.");
  const palette = [];
  const paletteSlot = new Map();
  const usedBindings = new Map();
  for (const [key, reference] of [...referenced.entries()].sort(([, first], [, second]) => first.tileset.firstgid - second.tileset.firstgid || first.localId - second.localId)) {
    const binding = bindingForTileset(reference.tileset, bindingInputs);
    if (!binding) { errors.push(`Tileset ${reference.tileset.sourceName ?? reference.tileset.name} needs exactly one explicit asset binding.`); continue; }
    const asset = assets.get(binding.assetId);
    if (!asset) { errors.push(`Tileset binding ${binding.sourceName} references missing asset ${binding.assetId}.`); continue; }
    const frames = Math.max(1, Number(asset.frames ?? 1));
    if (reference.localId >= frames) { errors.push(`Tileset ${reference.tileset.sourceName ?? reference.tileset.name} local tile ${reference.localId} exceeds asset ${asset.id}'s ${frames} frame${frames === 1 ? "" : "s"}.`); continue; }
    if (asset.type !== "tileset") warnings.push(`Asset ${asset.id} is not typed as a tileset; review its atlas metadata before applying.`);
    usedBindings.set(normalizeBindingKey(binding.sourceName), binding.assetId);
    const tilesetKey = sha256Hex(canonicalJson({ sourceName: reference.tileset.sourceName, name: reference.tileset.name, firstgid: reference.tileset.firstgid })).slice(0, 12);
    const id = `tiled-${tilesetKey}-tile-${reference.localId}`;
    paletteSlot.set(key, palette.length + 1);
    palette.push({
      id,
      name: `${reference.tileset.name ?? reference.tileset.sourceName} ${reference.localId}`,
      assetId: asset.id,
      frame: reference.localId,
      drawOffsetX: 0,
      drawOffsetY: 0,
      anchor: projection.type === "dimetric-2:1" ? "bottom-center" : "top-left",
      probability: 1,
      transforms: { horizontal: true, vertical: true, diagonal: true },
    });
  }
  const visualLayers = parsed.layers.map((layer, layerIndex) => {
    const offsetCellsX = Math.round(layer.offsetX / parsed.tileWidth);
    const offsetCellsY = Math.round(layer.offsetY / parsed.tileHeight);
    const cells = [];
    for (const chunk of layer.chunks) for (let index = 0; index < chunk.gids.length; index += 1) {
      const raw = Number(chunk.gids[index]) >>> 0;
      const gid = raw & TILED_GID_MASK;
      if (!gid) continue;
      const tileset = tileSetForGid(parsed.tilesets, gid);
      if (!tileset) continue;
      const slot = paletteSlot.get(`${tileset.firstgid}:${gid - tileset.firstgid}`);
      if (!slot) continue;
      const x = chunk.x + offsetCellsX + (index % chunk.width) + shiftX;
      const y = chunk.y + offsetCellsY + Math.floor(index / chunk.width) + shiftY;
      cells.push({ x, y, word: encodeTileCell({ slot, flipH: Boolean(raw & TILED_FLIP_H), flipV: Boolean(raw & TILED_FLIP_V), flipD: Boolean(raw & TILED_FLIP_D) }) });
    }
    const properties = layer.properties ?? {};
    const requestedRole = properties["looplab.role"];
    const role = ["ground-static", "interleaved", "foreground"].includes(requestedRole) ? requestedRole : projection.type === "dimetric-2:1" ? "interleaved" : "ground-static";
    const requestedBlend = String(properties["looplab.blendMode"] ?? "normal");
    const blendMode = ["normal", "multiply", "screen", "overlay", "darken", "lighten"].includes(requestedBlend) ? requestedBlend : "normal";
    if (requestedBlend !== blendMode) warnings.push(`Layer ${layer.name} requested unsupported blend mode ${requestedBlend}; canonical projection uses normal.`);
    return {
      id: stableId(`tiled-layer-${layer.id}`, `tiled-layer-${layerIndex + 1}`),
      name: String(layer.name),
      role,
      visible: layer.visible !== false,
      locked: false,
      opacity: Math.max(0, Math.min(1, Number(layer.opacity ?? 1))),
      blendMode,
      parallaxX: Math.max(0, Math.min(8, Number(layer.parallaxX ?? 1))),
      parallaxY: Math.max(0, Math.min(8, Number(layer.parallaxY ?? 1))),
      supportZ: finite(properties["looplab.supportZ"]) ? Math.max(-1024, Math.min(1024, Number(properties["looplab.supportZ"]))) : 0,
      chunks: columns > 0 && rows > 0 ? createSparseChunks(columns, rows, cells) : [],
      terrainChunks: [],
    };
  });
  const existing = map.tileProgram ? normalizeTileProgram(map.tileProgram) : null;
  if (existing && input.replaceExisting !== true) errors.push("The target map already has a visual tile program. Set replaceExisting=true only after reviewing this preview.");
  if (existing && (existing.columns !== columns || existing.rows !== rows) && existing.collisionLayers.some((layer) => layer.chunks.length)) errors.push("The Tiled grid dimensions differ from existing authored tile collision. Resize or migrate collision explicitly before replacing visual tiles.");
  const program = normalizeTileProgram({
    schemaVersion: LOOPLAB_TILE_PROGRAM_SCHEMA,
    collisionOwner: "authored-map",
    cellWidth: projection.tileWidth,
    cellHeight: projection.tileHeight,
    columns: Math.max(1, columns),
    rows: Math.max(1, rows),
    chunkSize: LOOPLAB_TILE_PROGRAM_LIMITS.chunkSize,
    variationSeed: existing?.variationSeed ?? 1,
    palette,
    terrainSets: [],
    collisionProfiles: existing?.collisionProfiles ?? [],
    layers: visualLayers,
    collisionLayers: existing?.collisionLayers ?? [],
  });
  const logicalWidth = projection.type === "dimetric-2:1" ? columns * 128 : columns * projection.tileWidth;
  const logicalHeight = projection.type === "dimetric-2:1" ? rows * 128 : rows * projection.tileHeight;
  const changesProjection = !sameProjection(map.projection, projection);
  const changesSize = Number(map.width) !== logicalWidth || Number(map.height) !== logicalHeight;
  if (changesProjection && input.allowProjectionChange !== true) errors.push("The imported map projection differs from the target. Set allowProjectionChange=true only after reviewing the exact projection change.");
  if (changesSize && input.resizeMap !== true) errors.push(`The imported logical map size is ${logicalWidth}×${logicalHeight}, not ${map.width}×${map.height}. Set resizeMap=true only after reviewing object, route, and camera bounds.`);
  return {
    mapId: map.id,
    program,
    mapChanges: { projection, grid: projection.type === "dimetric-2:1" ? 128 : projection.tileWidth, width: logicalWidth, height: logicalHeight },
    normalizedGrid: { columns, rows, originShift: { x: shiftX, y: shiftY } },
    usedBindings: [...usedBindings.entries()].map(([sourceName, assetId]) => ({ sourceName, assetId })),
    errors: [...new Set(errors)],
    warnings: [...new Set(warnings)].slice(0, LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumWarnings),
  };
}

function exchangeEnvelope(project) {
  const value = project?.authoring?.communityExchange;
  return value && typeof value === "object" && !Array.isArray(value)
    ? value
    : { schemaVersion: LOOPLAB_COMMUNITY_EXCHANGE_SCHEMA, entries: [] };
}

export function upsertCommunityExchange(project, entry) {
  const next = clone(project);
  const envelope = exchangeEnvelope(next);
  const entries = Array.isArray(envelope.entries) ? clone(envelope.entries) : [];
  const index = entries.findIndex((candidate) => candidate.id === entry.id);
  if (index >= 0) entries[index] = clone(entry);
  else entries.push(clone(entry));
  if (entries.length > LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumEntries) throw new Error(`Community exchange cannot exceed ${LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumEntries} retained entries.`);
  entries.sort((first, second) => compareText(first.id, second.id));
  next.authoring = { ...(next.authoring ?? {}), communityExchange: { schemaVersion: LOOPLAB_COMMUNITY_EXCHANGE_SCHEMA, entries } };
  return next;
}

function publicEntry(entry, includeSource = false) {
  return {
    id: entry.id,
    kind: entry.kind,
    format: entry.format,
    sourceName: entry.sourceName,
    sourceSha256: entry.sourceSha256,
    sourceLength: entry.sourceLength,
    parsedDigest: entry.parsedDigest,
    projectionDigest: entry.projectionDigest,
    target: clone(entry.target),
    unknownPaths: clone(entry.unknownPaths ?? []),
    warnings: clone(entry.warnings ?? []),
    dependencies: (entry.dependencies ?? []).map((dependency) => ({ sourceName: dependency.sourceName, format: dependency.format, sourceSha256: dependency.sourceSha256, sourceLength: dependency.sourceLength })),
    ...(includeSource ? { sourceText: entry.sourceText, dependenciesWithSource: clone(entry.dependencies ?? []) } : {}),
  };
}

function currentProjection(project, entry) {
  if (entry.kind === "tiled") {
    const map = mapForProject(project, entry.target?.mapId);
    if (!map) return null;
    return canonicalSha256({ map: { id: map.id, width: map.width, height: map.height, grid: map.grid, projection: map.projection }, tileProgram: map.tileProgram ?? null });
  }
  if (entry.kind === "aseprite") {
    const asset = (project.assets ?? []).find((candidate) => candidate.id === entry.target?.assetId);
    const machine = project.presentationProgram?.animation?.machines?.find((candidate) => candidate.id === entry.target?.machineId);
    if (!asset || !machine) return null;
    return canonicalSha256({ asset: { id: asset.id, type: asset.type, width: asset.width, height: asset.height, frameWidth: asset.frameWidth, frameHeight: asset.frameHeight, frames: asset.frames, columns: asset.columns }, machine });
  }
  return null;
}

export function inspectCommunityExchanges(project = {}, options = {}) {
  const envelope = exchangeEnvelope(project);
  const issues = [];
  const entries = [];
  if (envelope.schemaVersion !== LOOPLAB_COMMUNITY_EXCHANGE_SCHEMA) issues.push({ severity: "warning", code: "community-exchange-schema", message: `authoring.communityExchange.schemaVersion must be ${LOOPLAB_COMMUNITY_EXCHANGE_SCHEMA}.`, path: "authoring.communityExchange.schemaVersion" });
  if (!Array.isArray(envelope.entries)) issues.push({ severity: "warning", code: "community-exchange-entries", message: "authoring.communityExchange.entries must be an array.", path: "authoring.communityExchange.entries" });
  const ids = new Set();
  for (const [index, entry] of (Array.isArray(envelope.entries) ? envelope.entries : []).entries()) {
    const path = `authoring.communityExchange.entries[${index}]`;
    const expectedSource = typeof entry?.sourceText === "string" ? `sha256:${sha256Hex(entry.sourceText)}` : null;
    const current = currentProjection(project, entry ?? {});
    const sourceValid = expectedSource !== null && expectedSource === entry?.sourceSha256;
    const currentStatus = current === null ? "target-missing" : current === entry?.projectionDigest ? "current" : "stale";
    if (!entry || typeof entry !== "object" || Array.isArray(entry)) issues.push({ severity: "warning", code: "community-exchange-entry", message: `${path} must be an object.`, path });
    else {
      if (!STABLE_ID.test(entry.id ?? "") || ids.has(entry.id)) issues.push({ severity: "warning", code: "community-exchange-id", message: `${path}.id must be a unique stable ID.`, path: `${path}.id` });
      ids.add(entry.id);
      if (!sourceValid) issues.push({ severity: "warning", code: "community-exchange-source-hash", message: `${entry.id ?? path} no longer matches its retained exact source SHA-256.`, path: `${path}.sourceText`, exchangeId: entry.id });
      if (currentStatus === "target-missing") issues.push({ severity: "warning", code: "community-exchange-target-missing", message: `${entry.id ?? path} references a missing canonical target.`, path: `${path}.target`, exchangeId: entry.id });
      else if (currentStatus === "stale") issues.push({ severity: "info", code: "community-exchange-stale", message: `${entry.id} remains exportable as its original source, but canonical LoopLab source changed after import.`, path: `${path}.projectionDigest`, exchangeId: entry.id });
    }
    if (entry && typeof entry === "object") entries.push({ ...publicEntry(entry, options.includeSource === true), sourceValid, currentProjectionDigest: current, status: currentStatus, byteIdenticalExportAvailable: sourceValid && currentStatus === "current" });
  }
  return {
    schemaVersion: LOOPLAB_COMMUNITY_EXCHANGE_REPORT_SCHEMA,
    present: Boolean(project?.authoring?.communityExchange),
    valid: issues.every((issue) => issue.severity !== "warning"),
    entryCount: entries.length,
    entries,
    issues,
    policy: LOOPLAB_COMMUNITY_EXCHANGE_POLICY,
  };
}

export function previewTiledImport(project = {}, input = {}, options = {}) {
  const format = resolveTiledFormat(input.sourceName, input.format, input.sourceText);
  const source = sourceReceipt(input.sourceName, input.sourceText, format === "tmx" ? "tmx" : "json");
  const dependencies = dependencyIndex(input.dependencies);
  const parsed = format === "tmx" ? parseTmx(source.sourceText, dependencies) : parseTiledJson(source.sourceText, dependencies);
  const projection = buildTiledProjection(project, input, parsed);
  const exchangeId = stableId(input.exchangeId, `tiled-${source.sourceSha256.slice(7, 19)}`);
  const targetProjectionDigest = canonicalSha256({ map: { id: projection.mapId, ...projection.mapChanges }, tileProgram: projection.program });
  const entry = {
    id: exchangeId,
    kind: "tiled",
    format: parsed.format,
    sourceName: source.sourceName,
    sourceSha256: source.sourceSha256,
    sourceLength: source.sourceLength,
    sourceText: source.sourceText,
    parsedDigest: parsed.parsedDigest,
    projectionDigest: targetProjectionDigest,
    target: { mapId: projection.mapId },
    dependencies: dependencies.receipts,
    unknownPaths: parsed.unknownPaths,
    warnings: projection.warnings,
    normalizedGrid: projection.normalizedGrid,
    collisionOwner: "authored-map",
  };
  const digestPayload = { kind: "tiled", sourceDigest: options.sourceDigest ?? null, input: { exchangeId, mapId: projection.mapId, replaceExisting: input.replaceExisting === true, resizeMap: input.resizeMap === true, allowProjectionChange: input.allowProjectionChange === true, assetBindings: projection.usedBindings }, sourceSha256: source.sourceSha256, dependencyDigests: dependencies.receipts.map((dependency) => dependency.sourceSha256), parsedDigest: parsed.parsedDigest, targetProjectionDigest, errors: projection.errors, warnings: projection.warnings };
  return {
    schemaVersion: LOOPLAB_COMMUNITY_EXCHANGE_PREVIEW_SCHEMA,
    kind: "tiled",
    sourceDigest: options.sourceDigest ?? null,
    previewDigest: canonicalSha256(digestPayload),
    applicable: projection.errors.length === 0,
    errors: projection.errors,
    warnings: projection.warnings,
    source: { ...source, sourceText: undefined },
    parsed: { format: parsed.format, orientation: parsed.orientation, tileWidth: parsed.tileWidth, tileHeight: parsed.tileHeight, infinite: parsed.infinite, tilesetCount: parsed.tilesets.length, tileLayerCount: parsed.layers.length, objectLayerCount: parsed.objectLayerCount, unknownPaths: parsed.unknownPaths },
    proposal: { mapId: projection.mapId, mapChanges: projection.mapChanges, tileProgram: projection.program, exchangeEntry: entry },
    authority: { providerUsed: false, persistsProject: false, grantsMutationAuthority: false, collisionChanged: false, exactApplyRequiresCurrentSourceAndPreviewDigest: true },
    policy: LOOPLAB_COMMUNITY_EXCHANGE_POLICY,
  };
}

function asepriteFrames(document) {
  const collection = document?.frames;
  if (Array.isArray(collection)) return collection.map((frame, index) => ({ name: frame.filename ?? `frame-${index}`, ...frame }));
  if (collection && typeof collection === "object") return Object.entries(collection).map(([name, frame]) => ({ name, ...frame }));
  throw new Error("Aseprite JSON must contain frames as an array or hash.");
}

function tagFrameOrder(tag, frameCount) {
  const from = Number(tag.from);
  const to = Number(tag.to);
  if (!Number.isInteger(from) || !Number.isInteger(to) || from < 0 || to < from || to >= frameCount) throw new Error(`Aseprite tag ${tag.name ?? "unnamed"} has an invalid frame range.`);
  const forward = Array.from({ length: to - from + 1 }, (_, index) => from + index);
  if (tag.direction === "reverse") return [...forward].reverse();
  if (tag.direction === "pingpong") return forward.length < 2 ? forward : [...forward, ...forward.slice(1, -1).reverse()];
  if (tag.direction === "pingpong_reverse") {
    const reverse = [...forward].reverse();
    return reverse.length < 2 ? reverse : [...reverse, ...reverse.slice(1, -1).reverse()];
  }
  return forward;
}

function buildAsepriteProjection(project, input, document) {
  const asset = (project.assets ?? []).find((candidate) => candidate.id === input.assetId);
  if (!asset) throw new Error(`Aseprite import target asset ${String(input.assetId)} was not found.`);
  const frames = asepriteFrames(document);
  const errors = [];
  const warnings = [];
  if (frames.length < 1 || frames.length > LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumAsepriteFrames) errors.push("Aseprite frame count is empty or exceeds the bounded asset limit.");
  const metaWidth = Number(document.meta?.size?.w ?? asset.width);
  const metaHeight = Number(document.meta?.size?.h ?? asset.height);
  const first = frames[0] ?? {};
  const frameWidth = Number(first.sourceSize?.w ?? first.frame?.w);
  const frameHeight = Number(first.sourceSize?.h ?? first.frame?.h);
  if (![metaWidth, metaHeight, frameWidth, frameHeight].every((value) => Number.isInteger(value) && value > 0)) errors.push("Aseprite atlas and source frame dimensions must be positive integers.");
  const columns = Number.isInteger(metaWidth / frameWidth) ? metaWidth / frameWidth : 0;
  if (!columns) errors.push("Aseprite atlas width is not an exact multiple of the uniform source frame width.");
  for (const [index, frame] of frames.entries()) {
    const rectangle = frame.frame ?? {};
    const sourceSize = frame.sourceSize ?? {};
    const spriteSource = frame.spriteSourceSize ?? {};
    if (frame.rotated === true) errors.push(`Frame ${frame.name} is rotated; exchange v1 never guesses rotated atlas sampling.`);
    if (frame.trimmed === true || Number(spriteSource.x ?? 0) !== 0 || Number(spriteSource.y ?? 0) !== 0 || Number(sourceSize.w ?? frameWidth) !== frameWidth || Number(sourceSize.h ?? frameHeight) !== frameHeight) errors.push(`Frame ${frame.name} is trimmed or has a non-uniform source rectangle.`);
    const expectedX = (index % columns) * frameWidth;
    const expectedY = Math.floor(index / columns) * frameHeight;
    if (Number(rectangle.x) !== expectedX || Number(rectangle.y) !== expectedY || Number(rectangle.w) !== frameWidth || Number(rectangle.h) !== frameHeight) errors.push(`Frame ${frame.name} is not in row-major uniform-grid position ${expectedX},${expectedY},${frameWidth},${frameHeight}.`);
    if (!Number.isFinite(Number(frame.duration)) || Number(frame.duration) <= 0) errors.push(`Frame ${frame.name} requires a positive duration.`);
  }
  if (Number(asset.width) !== metaWidth || Number(asset.height) !== metaHeight) errors.push(`Asset ${asset.id} dimensions ${asset.width}×${asset.height} do not match Aseprite atlas ${metaWidth}×${metaHeight}.`);
  if (!String(asset.dataUrl ?? "").startsWith("data:image/")) errors.push(`Asset ${asset.id} must already contain the matching embedded image data URL.`);
  const rawTags = Array.isArray(document.meta?.frameTags) && document.meta.frameTags.length
    ? document.meta.frameTags
    : [{ name: "default", from: 0, to: Math.max(0, frames.length - 1), direction: "forward" }];
  if (rawTags.length > LOOPLAB_PRESENTATION_LIMITS.maximumAnimationStatesPerMachine) errors.push(`Aseprite tags exceed the ${LOOPLAB_PRESENTATION_LIMITS.maximumAnimationStatesPerMachine} animation-state limit.`);
  const states = [];
  const stateIds = new Set();
  for (const [index, tag] of rawTags.entries()) {
    let order;
    try { order = tagFrameOrder(tag, frames.length); } catch (error) { errors.push(error instanceof Error ? error.message : String(error)); continue; }
    if (order.length > LOOPLAB_PRESENTATION_LIMITS.maximumAnimationFramesPerState) { errors.push(`Aseprite tag ${tag.name ?? index} expands beyond ${LOOPLAB_PRESENTATION_LIMITS.maximumAnimationFramesPerState} frames.`); continue; }
    const durations = order.map((frameIndex) => Number(frames[frameIndex]?.duration));
    const uniqueDurations = [...new Set(durations)];
    if (uniqueDurations.length > 1 && input.allowTimingApproximation !== true) { errors.push(`Aseprite tag ${tag.name ?? index} uses per-frame durations that the current uniform-fps presentation state cannot represent. Set allowTimingApproximation=true only after reviewing the approximation.`); continue; }
    if (uniqueDurations.length > 1) warnings.push(`Tag ${tag.name ?? index} uses ${uniqueDurations.length} frame durations; canonical projection uses their mean FPS while exact durations remain in the source envelope.`);
    const meanDuration = durations.reduce((sum, value) => sum + value, 0) / Math.max(1, durations.length);
    const id = stableId(tag.name, `state-${index + 1}`);
    if (stateIds.has(id)) { errors.push(`Aseprite tag ${tag.name ?? index} normalizes to duplicate state ID ${id}.`); continue; }
    stateIds.add(id);
    if (tag.repeat !== undefined) warnings.push(`Aseprite tag ${tag.name ?? index} repeat count is preserved in source but projected as the presentation state's loop Boolean.`);
    states.push({ id, assetId: asset.id, frames: order, fps: Math.max(1, Math.min(60, 1000 / meanDuration)), loop: tag.repeat !== 1, interruptMode: "frame-end", reducedMotionFrame: order[0] ?? 0 });
  }
  const target = input.target;
  if (!target || !["object-id", "object-kind"].includes(target.type) || !STABLE_ID.test(String(target.id ?? ""))) errors.push("Aseprite presentation import requires target {type: object-id|object-kind, id: stable-id}.");
  const machineId = stableId(input.machineId, `aseprite-${asset.id}`);
  const machine = { id: machineId, enabled: true, target: { type: target?.type ?? "object-kind", id: target?.id ?? "player" }, initialState: states[0]?.id ?? "", states, transitions: [] };
  const presentation = normalizePresentationProgram(project.presentationProgram ?? {});
  const existingIndex = presentation.animation.machines.findIndex((candidate) => candidate.id === machineId);
  if (existingIndex >= 0 && input.replaceExisting !== true) errors.push(`Presentation machine ${machineId} already exists. Set replaceExisting=true only after reviewing the exact replacement.`);
  if (existingIndex >= 0) presentation.animation.machines[existingIndex] = machine;
  else presentation.animation.machines.push(machine);
  presentation.animation.enabled = true;
  const updatedAsset = { ...clone(asset), frameWidth, frameHeight, frames: frames.length, columns };
  const projectionDigest = canonicalSha256({ asset: { id: updatedAsset.id, type: updatedAsset.type, width: updatedAsset.width, height: updatedAsset.height, frameWidth, frameHeight, frames: frames.length, columns }, machine });
  return { assetId: asset.id, machineId, updatedAsset, presentation, machine, frames, errors: [...new Set(errors)], warnings: [...new Set(warnings)].slice(0, LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumWarnings), projectionDigest };
}

export function previewAsepriteImport(project = {}, input = {}, options = {}) {
  const source = sourceReceipt(input.sourceName, input.sourceText, "json");
  let document;
  try { document = JSON.parse(source.sourceText); } catch (error) { throw new Error(`Aseprite JSON is invalid: ${error instanceof Error ? error.message : String(error)}`); }
  if (!document || typeof document !== "object" || Array.isArray(document)) throw new Error("Aseprite JSON must be an object.");
  const projection = buildAsepriteProjection(project, input, document);
  const exchangeId = stableId(input.exchangeId, `aseprite-${source.sourceSha256.slice(7, 19)}`);
  const unknownPaths = Object.keys(document).filter((key) => !["frames", "meta"].includes(key)).map((key) => `$.${key}`).slice(0, LOOPLAB_COMMUNITY_EXCHANGE_LIMITS.maximumUnknownPaths);
  const parsedDigest = canonicalSha256(document);
  const entry = {
    id: exchangeId,
    kind: "aseprite",
    format: Array.isArray(document.frames) ? "aseprite-json-array" : "aseprite-json-hash",
    sourceName: source.sourceName,
    sourceSha256: source.sourceSha256,
    sourceLength: source.sourceLength,
    sourceText: source.sourceText,
    parsedDigest,
    projectionDigest: projection.projectionDigest,
    target: { assetId: projection.assetId, machineId: projection.machineId },
    dependencies: [],
    unknownPaths,
    warnings: projection.warnings,
  };
  const digestPayload = { kind: "aseprite", sourceDigest: options.sourceDigest ?? null, sourceSha256: source.sourceSha256, parsedDigest, projectionDigest: projection.projectionDigest, input: { exchangeId, assetId: projection.assetId, machineId: projection.machineId, target: input.target, replaceExisting: input.replaceExisting === true, allowTimingApproximation: input.allowTimingApproximation === true }, errors: projection.errors, warnings: projection.warnings };
  return {
    schemaVersion: LOOPLAB_COMMUNITY_EXCHANGE_PREVIEW_SCHEMA,
    kind: "aseprite",
    sourceDigest: options.sourceDigest ?? null,
    previewDigest: canonicalSha256(digestPayload),
    applicable: projection.errors.length === 0,
    errors: projection.errors,
    warnings: projection.warnings,
    source: { ...source, sourceText: undefined },
    parsed: { format: entry.format, frameCount: projection.frames.length, tagCount: projection.machine.states.length, atlas: { width: document.meta?.size?.w ?? null, height: document.meta?.size?.h ?? null }, unknownPaths },
    proposal: { assetId: projection.assetId, updatedAsset: projection.updatedAsset, machineId: projection.machineId, presentationProgram: projection.presentation, exchangeEntry: entry },
    authority: { providerUsed: false, persistsProject: false, grantsMutationAuthority: false, collisionChanged: false, exactApplyRequiresCurrentSourceAndPreviewDigest: true },
    policy: LOOPLAB_COMMUNITY_EXCHANGE_POLICY,
  };
}

export function exportCommunityExchange(project = {}, input = {}) {
  const report = inspectCommunityExchanges(project, { includeSource: true });
  const entry = report.entries.find((candidate) => candidate.id === input.exchangeId);
  if (!entry) throw new Error(`Community exchange ${String(input.exchangeId)} was not found.`);
  if (!entry.sourceValid) throw new Error("The retained exact source hash is invalid; export is blocked rather than returning unverified bytes.");
  const exact = entry.status === "current";
  if (!exact && input.allowStaleOriginal !== true) throw new Error("Canonical LoopLab source changed after import. Set allowStaleOriginal=true only to export the clearly-labelled original source, not the current canonical projection.");
  return {
    schemaVersion: LOOPLAB_COMMUNITY_EXCHANGE_EXPORT_SCHEMA,
    exchangeId: entry.id,
    kind: entry.kind,
    format: entry.format,
    filename: entry.sourceName,
    sourceText: entry.sourceText,
    sourceSha256: entry.sourceSha256,
    sourceLength: entry.sourceLength,
    byteIdentical: exact,
    semanticsPreservingForCurrentSource: exact,
    status: exact ? "exact-unchanged-source" : "stale-original-source",
    currentProjectionDigest: entry.currentProjectionDigest,
    importedProjectionDigest: entry.projectionDigest,
    warning: exact ? null : "This is the exact originally imported document. It does not include later canonical LoopLab edits.",
    policy: LOOPLAB_COMMUNITY_EXCHANGE_POLICY.roundTrip,
  };
}

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const phaserPackagePath = path.join(repositoryRoot, "node_modules", "phaser", "package.json");
const phaserBundlePath = path.join(repositoryRoot, "node_modules", "phaser", "dist", "phaser.min.js");
const generatedDirectory = path.join(repositoryRoot, "lib", "generated");
const generatedModulePath = path.join(generatedDirectory, "looplab-phaser-browser-bundle.mjs");

const packageMetadata = JSON.parse(await readFile(phaserPackagePath, "utf8"));
const sourceBundle = await readFile(phaserBundlePath, "utf8");
const browserBundle = sourceBundle.replaceAll("</script", "<\\/script");
const sha256 = createHash("sha256").update(browserBundle).digest("hex");
const bytes = Buffer.byteLength(browserBundle);
const generated = [
  "// Generated by scripts/generate-runtime-bundles.mjs. Do not edit by hand.",
  `export const LOOPLAB_PHASER_BROWSER_VERSION = ${JSON.stringify(packageMetadata.version)};`,
  `export const LOOPLAB_PHASER_BROWSER_SHA256 = ${JSON.stringify(sha256)};`,
  `export const LOOPLAB_PHASER_BROWSER_BYTES = ${bytes};`,
  `export const LOOPLAB_PHASER_BROWSER_BUNDLE = ${JSON.stringify(browserBundle)};`,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(generatedModulePath, "utf8");
  } catch {
    // The mismatch message below is more useful than the raw read failure.
  }
  if (current !== generated) {
    throw new Error("The generated Phaser browser bundle is stale. Run npm run runtime-bundles:generate.");
  }
  console.log(`Pinned Phaser ${packageMetadata.version} browser bundle verified (${bytes.toLocaleString()} bytes, sha256:${sha256.slice(0, 12)}...).`);
} else {
  await mkdir(generatedDirectory, { recursive: true });
  await writeFile(generatedModulePath, generated, "utf8");
  console.log(`Generated Phaser ${packageMetadata.version} browser bundle (${bytes.toLocaleString()} bytes, sha256:${sha256.slice(0, 12)}...).`);
}

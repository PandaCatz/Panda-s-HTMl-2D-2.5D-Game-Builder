import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedDirectory = path.join(repositoryRoot, "lib", "generated");
const checkOnly = process.argv.includes("--check");

function escapedInlineScript(source) {
  return source.replaceAll("</script", "<\\/script");
}

function bundleMetadata(source) {
  const browserBundle = escapedInlineScript(source);
  return {
    browserBundle,
    bytes: Buffer.byteLength(browserBundle),
    sha256: createHash("sha256").update(browserBundle).digest("hex"),
  };
}

function generatedModule({ id, version, source }) {
  const prefix = id.toUpperCase();
  const metadata = bundleMetadata(source);
  return {
    ...metadata,
    source: [
      "// Generated by scripts/generate-runtime-bundles.mjs. Do not edit by hand.",
      `export const LOOPLAB_${prefix}_BROWSER_VERSION = ${JSON.stringify(version)};`,
      `export const LOOPLAB_${prefix}_BROWSER_SHA256 = ${JSON.stringify(metadata.sha256)};`,
      `export const LOOPLAB_${prefix}_BROWSER_BYTES = ${metadata.bytes};`,
      `export const LOOPLAB_${prefix}_BROWSER_BUNDLE = ${JSON.stringify(metadata.browserBundle)};`,
      "",
    ].join("\n"),
  };
}

async function packageVersion(packageName) {
  return JSON.parse(await readFile(path.join(repositoryRoot, "node_modules", packageName, "package.json"), "utf8")).version;
}

async function pixiBrowserBundle() {
  const pixiDirectory = path.join(repositoryRoot, "node_modules", "pixi.js", "dist");
  const [runtime, strictCspPolyfill] = await Promise.all([
    readFile(path.join(pixiDirectory, "pixi.min.js"), "utf8"),
    readFile(path.join(pixiDirectory, "packages", "unsafe-eval.min.js"), "utf8"),
  ]);
  // Pixi's unfortunately named `unsafe-eval` package does the opposite of what
  // the name suggests: loaded after PIXI, it replaces generated synchronizers
  // with official static implementations so the runtime works without the CSP
  // `unsafe-eval` capability. Keep both same-version browser UMDs under one hash.
  return `${runtime}\n${strictCspPolyfill}`;
}

async function melonBrowserBundle() {
  const result = await build({
    absWorkingDir: repositoryRoot,
    stdin: {
      contents: 'export { Application, Camera2d, Renderable, Stage, state, CANVAS, boot, version } from "melonjs";',
      loader: "js",
      resolveDir: repositoryRoot,
      sourcefile: "looplab-melon-browser-entry.mjs",
    },
    bundle: true,
    format: "iife",
    globalName: "LoopLabMelon",
    platform: "browser",
    target: ["es2020"],
    minify: true,
    treeShaking: true,
    legalComments: "inline",
    write: false,
    logLevel: "silent",
  });
  const output = result.outputFiles?.[0]?.text;
  if (!output) throw new Error("esbuild produced no melonJS browser adapter output.");
  return output;
}

const bundles = [
  {
    id: "phaser",
    version: await packageVersion("phaser"),
    source: await readFile(path.join(repositoryRoot, "node_modules", "phaser", "dist", "phaser.min.js"), "utf8"),
  },
  {
    id: "pixi",
    version: await packageVersion("pixi.js"),
    source: await pixiBrowserBundle(),
  },
  {
    id: "melon",
    version: await packageVersion("melonjs"),
    source: await melonBrowserBundle(),
  },
].map((bundle) => ({ ...bundle, generated: generatedModule(bundle) }));

await mkdir(generatedDirectory, { recursive: true });
for (const bundle of bundles) {
  const generatedModulePath = path.join(generatedDirectory, `looplab-${bundle.id}-browser-bundle.mjs`);
  if (checkOnly) {
    let current = "";
    try {
      current = await readFile(generatedModulePath, "utf8");
    } catch {
      // The mismatch message below is more useful than the raw read failure.
    }
    if (current !== bundle.generated.source) {
      throw new Error(`The generated ${bundle.id} browser bundle is stale. Run npm run runtime-bundles:generate.`);
    }
    console.log(`Pinned ${bundle.id} ${bundle.version} browser bundle verified (${bundle.generated.bytes.toLocaleString()} bytes, sha256:${bundle.generated.sha256.slice(0, 12)}...).`);
  } else {
    await writeFile(generatedModulePath, bundle.generated.source, "utf8");
    console.log(`Generated ${bundle.id} ${bundle.version} browser bundle (${bundle.generated.bytes.toLocaleString()} bytes, sha256:${bundle.generated.sha256.slice(0, 12)}...).`);
  }
}

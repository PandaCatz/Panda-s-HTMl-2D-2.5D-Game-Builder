import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { buildAgentGuideArtifacts } from "../lib/looplab-agent-guide-navigation.mjs";
import { LOOPLAB_EXPORTED_RUNTIME_VERSION } from "../lib/looplab-versions.mjs";

const projectRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const canonicalGuidePath = resolve(projectRoot, "docs", "AI_AGENT_GUIDE.md");
const publicGuidePath = resolve(projectRoot, "public", "AI_AGENT_GUIDE.md");
const publicIndexPath = resolve(projectRoot, "public", "agent-guide-index.json");
const generatedModulePath = resolve(projectRoot, "lib", "generated", "looplab-agent-guide-index.mjs");
const checkOnly = process.argv.includes("--check");

function normalizeLineEndings(value) {
  return typeof value === "string" ? value.replace(/\r\n?/g, "\n") : value;
}

const runtimeMajorMinor = LOOPLAB_EXPORTED_RUNTIME_VERSION.split(".").slice(0, 2).join(".");
const source = (await readFile(canonicalGuidePath, "utf8"))
  .replace(/(\b(?:Exported )?[Rr]untime API )\d+\.\d+/g, `$1${runtimeMajorMinor}`);
const { documentMarkdown, index } = buildAgentGuideArtifacts(source);
const publicIndex = `${JSON.stringify(index, null, 2)}\n`;
const generatedModule = `// Generated by scripts/generate-agent-guide-navigation.mjs. Do not edit directly.\nexport const LOOPLAB_AGENT_GUIDE_INDEX = Object.freeze(${JSON.stringify(index, null, 2)});\n`;
const outputs = [
  [canonicalGuidePath, documentMarkdown],
  [publicGuidePath, documentMarkdown],
  [publicIndexPath, publicIndex],
  [generatedModulePath, generatedModule],
];

if (checkOnly) {
  const stale = [];
  for (const [path, expected] of outputs) {
    let actual = null;
    try {
      actual = await readFile(path, "utf8");
    } catch {
      // A missing generated artifact is drift and is reported like any other mismatch.
    }
    if (normalizeLineEndings(actual) !== normalizeLineEndings(expected)) stale.push(path);
  }
  if (stale.length) {
    throw new Error(`AI Agent Guide navigation is stale. Run npm run agent-guide:generate. Mismatched artifacts: ${stale.join(", ")}`);
  }
  process.stdout.write(`${JSON.stringify({ ok: true, mode: "check", sourceDigest: index.source.digest, indexDigest: index.indexDigest, headingCount: index.source.headingCount })}\n`);
} else {
  for (const [path, contents] of outputs) await writeFile(path, contents, "utf8");
  process.stdout.write(`${JSON.stringify({ ok: true, mode: "generate", sourceDigest: index.source.digest, indexDigest: index.indexDigest, headingCount: index.source.headingCount, outputs: outputs.map(([path]) => path) })}\n`);
}
